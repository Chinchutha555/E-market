              <strong>๕. สิทธิของผู้ให้เช่า</strong>
              <p class="indent-paragraph">
                ผู้ให้เช่า หรือตัวแทน หรือเจ้าหน้าที่ของผู้ให้เช่า สามารถเข้าตรวจสอบทรัพย์สินที่เช่าได้ ทุกเวลา หากเห็นว่าทรัพย์สินที่เช่าอยู่ในสภาพชำรุด ทรุดโทรม หรือน่าจะเป็นอันตรายเสียหาย มีสิทธิแจ้งเตือนให้ผู้เช่าหรือตัวแทนผู้เช่าหรือผู้ครอบครองทรัพย์สินที่เช่าดำเนินการแก้ไขปรับปรุงหรือซ่อมแซมให้อยู่ในสภาพดีได้ และเมื่อได้แจ้งให้ดำเนินการแก้ไขปรับปรุงหรือซ่อมแซมแล้ว แต่ผู้เช่าหรือตัวแทนของผู้เช่าหรือผู้ครอบครองทรัพย์สินที่เช่ายังคงละเลยเพิกเฉย หากเกิดความเสียหายขึ้นไม่ว่ากับทรัพย์สินหรือบุคคลใด ผู้เช่าหรือตัวแทนของผู้เช่าหรือผู้ครอบครองทรัพย์สินที่เช่า รวมถึงบริวารจะต้องรับผิดชอบทุกกรณี และกรณีเช่นนี้หากความเสียหายมีสภาพร้ายแรงผู้ให้เช่ามีสิทธิบอกเลิกสัญญาได้ทันที
              </p>

