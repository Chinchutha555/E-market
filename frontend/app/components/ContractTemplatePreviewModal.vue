                <p><strong>๔.๔</strong> ผู้เช่าต้องทำการค้าด้วยตนเอง และห้ามมิให้นำทรัพย์สินที่เช่าไปให้บุคคลอื่นเช่าช่วง หรือโอนสิทธิการเช่าทั้งหมดหรือบางส่วน เว้นแต่ได้รับความยินยอมจากผู้ให้เช่าเป็นลายลักษณ์อักษร หรือในกรณีที่ได้รับความยินยอมจากผู้ให้เช่า นอกจากค่าเช่ารายเดือนที่ต้องชำระในแต่ละเดือนแล้ว ผู้เช่าและหรือผู้เช่าช่วงตกลงยินยอมชำระค่าตอบแทนการให้ความยินยอมดังกล่าวแก่ผู้ให้เช่าอีกร้อยละ ๒๐ ของรายได้จากค่าเช่าช่วงเป็นรายเดือน หากตรวจสอบพบว่าผู้เช่าดำเนินการโดยไม่ได้รับอนุญาตจะต้องชำระค่าปรับในอัตราค่าเช่าหนึ่งปี และ/หรือ ผู้ให้เช่าอาจบอกเลิกสัญญาได้</p>
                <p><strong>๔.๕</strong> ต้องทำการค้าทุกวันเสาร์และวันอาทิตย์ หรือวันที่ผู้ให้เช่ากำหนดให้เป็นวันทำการเป็นประจำอย่างต่อเนื่อง และตามเวลาที่ผู้ให้เช่ากำหนด ผู้เช่าจะหยุดทำการค้าต่อเนื่องติดต่อกันเกินกว่า ๓ สัปดาห์มิได้ หากมีความจำเป็นจะต้องหยุดทำการค้าติดต่อกันเกินกว่า ๓ สัปดาห์ ให้แจ้งเหตุผลและความจำเป็นโดยทำเป็นลายลักษณ์อักษรยื่นต่อผู้ให้เช่า หรือตัวแทน หรือเจ้าหน้าที่ของผู้ให้เช่า เว้นแต่กรณีจำเป็นเร่งด่วน หรือสุดวิสัยจะแจ้งด้วยวาจาไว้ก่อนที่จะแจ้งเป็นลายลักษณ์อักษรก็ได้</p>
                <p><strong>๔.๖</strong> ต้องสงวนรักษาทรัพย์สินที่เช่าเสมือนวิญญูชนจะพึงสงวนรักษาทรัพย์สินของตนเอง และรักษาความสะอาดตามปกติวิสัย และตามกฎหมาย ทั้งจะต้องไม่กระทำการใดอันเป็นการก่อให้เกิดเหตุเดือดร้อนรำคาญ หรือเสื่อมเสียสุขภาพของบุคคลอื่นใดด้วย</p>
                <p><strong>๔.๗</strong> ต้องยินยอมให้ผู้ให้เช่าปรับปรุงซ่อมแซมทรัพย์สินที่เช่า หรือก่อสร้างอาคารแผงค้ากึ่งถาวรหรือถาวร จัดระเบียบแผงค้าตามที่ผู้ให้เช่ากำหนด ผู้เช่าต้องอำนวยความสะดวกโดยการขนย้ายสินค้า สิ่งของสัมภาระและทรัพย์สินทั้งปวงซึ่งเป็นของผู้เช่าหรือบริวาร หรือรื้อถอนสิ่งปลูกสร้างออกจากบริเวณทรัพย์สินที่เช่าภายในเวลาที่ผู้ให้เช่ากำหนด หากผู้เช่าไม่ดำเนินการในเวลาที่กำหนด ผู้เช่ายินยอมให้ผู้ให้เช่า หรือตัวแทน หรือเจ้าหน้าที่ของผู้ให้เช่า ขนย้ายสินค้า สิ่งของสัมภาระและทรัพย์สินทั้งปวงเพื่อนำไปเก็บไว้ในสถานที่ที่เหมาะสม โดยผู้เช่าจะไม่ฟ้องร้องเรียกค่าเสียหายหรือดำเนินคดีทั้งทางแพ่งและทางอาญากับผู้ให้เช่า หรือตัวแทน หรือเจ้าหน้าที่ของผู้ให้เช่าแต่อย่างใด และกรณีมีการปรับปรุงซ่อมแซมทรัพย์สินที่เช่าไม่ว่าจะดำเนินการโดยผู้เช่า หรือผู้ให้เช่า ให้สิ่งของสัมภาระที่นำมาใช้ในการปรับปรุงซ่อมแซมนั้นตกเป็นส่วนควบกับทรัพย์สินที่เช่า</p>
                <p><strong>๔.๘</strong> ต้องรับผิดชอบในความเสียหายหรือบุบสลายใด ๆ อันเกิดขึ้นแก่ทรัพย์สินที่เช่า เพราะความผิดของผู้เช่า ผู้เช่าช่วง หรือตัวแทนของผู้เช่า หรือตัวแทนของผู้เช่าช่วง รวมตลอดไปจนถึงความเสียหายอันเกิดจากบุคคลภายนอกด้วย</p>
                <p><strong>๔.๙</strong> ห้ามมิให้ผู้เช่าหรือผู้เช่าช่วง ใช้ หรืออนุญาต หรือยินยอมให้ผู้ใดใช้เครื่องเสียง เครื่องขยายเสียง หรือโทรทัศน์หรือจอภาพ หรือเครื่องมือเทคโนโลยีสารสนเทศอื่นใดในทำนองเดียวกันอันอาจก่อให้เกิดมลภาวะทางด้านแสง เสียง ฝุ่นควัน หรือก่อความเดือดร้อนรำคาญแก่ผู้เช่ารายอื่นหรือประชาชนโดยทั่วไป เว้นแต่ จะได้รับอนุญาตเป็นลายลักษณ์อักษรจากผู้ให้เช่าเป็นรายกรณีไป ในกรณีที่ผู้เช่าได้รับอนุญาตให้ดำเนินการดังกล่าว ผู้เช่าจะต้องควบคุมมิให้เกิดมลภาวะรบกวนหรือก่อความเดือดร้อนรำคาญแก่ผู้เช่ารายอื่นหรือประชาชน หรือผู้ที่อยู่ในบริเวณใกล้เคียง หรือผู้ที่สัญจรไปมาในบริเวณนั้นอย่างเคร่งครัด หากเกิดความเสียหายขึ้นไม่ว่ากรณีใด ผู้เช่าจะต้องเป็นผู้รับผิดชอบทั้งสิ้น</p>
                <p><strong>๔.๑๐</strong> ห้ามมิให้ผู้เช่าหรือผู้เช่าช่วงทำการติดป้ายโฆษณา หรือแจกใบปลิว หรือกระทำการใดในทำนองเดียวกัน เว้นแต่จะได้รับอนุญาตเป็นลายลักษณ์อักษรจากผู้ให้เช่า</p>
                <p><strong>๔.๑๑</strong> จะต้องซ่อมวัสดุในการตั้งแผงค้าเมื่อเกิดการชำรุดเสียหาย ไม่ว่าผู้ให้เช่า หรือตัวแทนหรือเจ้าหน้าที่ของผู้ให้เช่าสั่งให้แก้ไขปรับปรุงหรือไม่ก็ตาม</p>
                <p><strong>๔.๑๒</strong> ห้ามมิให้ผู้เช่าหรือผู้เช่าช่วงทำการใดซึ่งอาจเป็นอันตรายแก่ต้นไม้ภายในบริเวณตลาดนัด</p>
                <p><strong>๔.๑๓</strong> ห้ามมิให้ผู้เช่าหรือผู้เช่าช่วงตั้งวางสินค้า สิ่งของ วัสดุอุปกรณ์ ห้อย แขวน เกะกะ รกรุงรัง กีดขวางทางเดิน ทางสัญจร หากผู้เช่าหรือผู้เช่าช่วงฝ่าฝืนจะต้องเสียค่าปรับให้แก่ผู้ให้เช่าเป็นเงิน ๕๐๐ บาท</p>
                <p><strong>๔.๑๔</strong> ห้ามมิให้ผู้เช่าหรือผู้เช่าช่วง เท หรือทิ้งสิ่งปฏิกูล มูลฝอย น้ำโสโครก หรือสิ่งอื่นใดลงบนทางเดิน ทางสัญจร รางระบายน้ำ และพื้นที่อื่น ๆ หากผู้เช่าหรือผู้เช่าช่วงฝ่าฝืนจะต้องเสียค่าปรับให้ผู้ให้เช่า ให้เป็นไปตามที่คณะกรรมการบริหารสำนักงานตลาดกรุงเทพมหานคร หรือสำนักงานตลาดกรุงเทพมหานคร กำหนด</p>
                <p><strong>๔.๑๕</strong> กรณีการประกอบการค้าประเภทอาหารปรุง เครื่องดื่ม จะต้องจัดทำป้ายแสดงราคาให้ชัดเจน และจัดให้มีถังดักไขมันทุกแผงค้า</p>
                <p><strong>๔.๑๖</strong> ต้องจัดให้มีป้ายหมายเลขแผงค้า ขนาดกว้าง ๒ นิ้ว คูณ ๔ นิ้ว ปิดไว้หน้าแผงค้าให้เห็นอย่างชัดเจน</p>
                <p><strong>๔.๑๗</strong> ต้องใช้เครื่องชั่ง ตวง วัด ที่ได้มาตรฐานตามกฎหมาย</p>
                <p><strong>๔.๑๘</strong> ห้ามมิให้ใช้เตาไฟที่มีความร้อนสูง หรือมีควัน อันอาจรบกวนบุคคลอื่น หรือเป็นอันตรายแก่แผงค้าข้างเคียง</p>
                <p><strong>๔.๑๙</strong> ต้องจัดให้มีสิ่งปกปิดอาหารสำเร็จรูป ผลไม้ ที่ปอกเปลือกหรือผ่าซีกตลอดจนผลไม้ที่แกะออกจากผลแล้ว จะต้องปกปิดในลักษณะที่ป้องกันฝุ่นและแมลงได้ตลอดเวลา</p>
                <p><strong>๔.๒๐</strong> ผู้ประกอบการค้าทุกประเภทจะต้องมีถุงหรือถังขยะของตนเอง และเมื่อเลิกทำการค้าจะต้องนำขยะไปทิ้ง ณ จุดที่ผู้ให้เช่าจัดให้</p>
                <p><strong>๔.๒๑</strong> ผู้ประกอบการค้าโครงการ ๑ - ๓๐ ให้เข้ามาจัดสินค้าและเปิดทำการค้าในวันศุกร์ วันเสาร์ และวันอาทิตย์ ได้ตั้งแต่เวลา ๐๕.๐๐ น. ถึงเวลา ๑๘.๐๐ น.</p>
                <p><strong>๔.๒๒</strong> การลำเลียงสินค้าเข้าแผงค้าในวันเสาร์ และวันอาทิตย์ จะต้องดำเนินการให้แล้วเสร็จไม่เกินเวลา ๑๒.๐๐ น.</p>
                <p><strong>๔.๒๓</strong> สินค้าที่นำมาจำหน่ายต้องเป็นสินค้าที่มีคุณภาพ สะอาด ปลอดภัย ไม่เสื่อมคุณภาพ หรือเป็นอันตรายต่อผู้บริโภค</p>
                <p><strong>๔.๒๔</strong> การประกอบการค้าจะต้องจำหน่ายสินค้าให้ถูกต้องตามประเภทที่ระบุไว้ในสัญญา จะเปลี่ยนแปลงประเภทสินค้าไม่ได้ เว้นแต่ได้รับอนุญาตจากผู้ให้เช่า และจะต้องชำระค่าเปลี่ยนแปลงประเภทสินค้าตามที่ผู้ให้เช่ากำหนด</p>
                <p><strong>๔.๒๕</strong> การตกแต่งปรับปรุงแผงค้า จะต้องได้รับอนุญาตจากผู้ให้เช่าทุกครั้ง และจะต้องเป็นไปตามรูปแบบที่ผู้ให้เช่ากำหนด</p>
